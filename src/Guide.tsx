export function Guide({ name }: { name: string }) {
  const key = guideKey(name)
  if (!key) return null
  const Icon = icons[key]
  if (!Icon) return null
  return (
    <Suspense fallback={null}>
      <Icon size="100%" strokeWidth={2} aria-hidden />
    </Suspense>
  )
}
