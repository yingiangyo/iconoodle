const SLUG = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/

export type IconSeed = { readonly name: string; readonly concept: string }

export function themeSlots(names: readonly string[], library: LibraryId): IconSeed[] {
  const used = new Set<string>()
  const slots: IconSeed[] = []
  for (const concept of names) {
    const spec = GLYPHS[concept]?.[library]
    if (!spec || used.has(spec.name) || !SLUG.test(spec.name)) continue
    used.add(spec.name)
    slots.push({ name: spec.name, concept })
  }
  return slots
}

export function guideConcept(library: LibraryId, concept: string | null, name: string): string | null {
  if (concept && GLYPHS[concept]?.[library]) return concept
  for (const [key, row] of Object.entries(GLYPHS)) {
    if (!row[library]) continue
    if (key === concept || key === name || Object.values(row).some((spec) => spec?.name === name)) return key
  }
  return null
}
